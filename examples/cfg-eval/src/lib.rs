//! Example-level, reusable cfg evaluation for parsed Rust source.
//!
//! This module does not compile any Rust code and never reads files or runs
//! macros. Given a parsed syn::File and a three-valued configuration
//! environment, it answers the question "which items would cfg keep?" and
//! rewrites the AST accordingly:
//!
//! - a condition evaluating to CfgState::False removes the item;
//! - a condition evaluating to CfgState::True strips the cfg/cfg_attr
//!   attribute;
//! - a condition still depending on unknown predicates keeps the original
//!   attribute untouched and records a diagnostic with the simplified
//!   condition and the path of the annotated syntax node.
//!
//! Supported predicates are bare names (unix), name/value pairs
//! (feature = "fast"), and the combinators all(...), any(...) and
//! not(...). Empty all() is true and empty any() is false.
//!
//! Recursion covers crate items, inline mod blocks, impl and trait items,
//! extern blocks, enum variants and named or tuple struct/enum fields.
//! External "mod foo;" declarations are reported as needing another file
//! instead of being opened. Conditions generated by cfg_attr (including
//! further cfg/cfg_attr attributes) are processed recursively under an
//! expansion budget.
//!
//! Any malformed cfg expression aborts the whole analysis with a positioned
//! syn::Error; no partially rewritten AST is produced.

use std::collections::BTreeMap;
use std::mem;

use proc_macro2::Span;
use syn::punctuated::{Pair, Punctuated};
use syn::spanned::Spanned;
use syn::{
    Attribute, Error, Expr, Field, Fields, File, ForeignItem, ImplItem, Item, Lit, Meta, Token,
    TraitItem, Variant,
};

/// Three-valued truth table for a cfg predicate.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CfgState {
    True,
    False,
    Unknown,
}

/// Why a diagnostic was emitted.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DiagnosticKind {
    /// A cfg/cfg_attr still depends on an unknown predicate and was kept.
    UnknownCondition,
    /// An external "mod foo;" declaration would require another file.
    ExternalModule,
}

/// A record produced while evaluating one file.
#[derive(Clone, Debug)]
pub struct Diagnostic {
    /// Path of the annotated syntax node, e.g. "outer::Inner::field0".
    pub path: String,
    pub kind: DiagnosticKind,
    /// Simplified cfg expression, for unknown conditions.
    pub condition: Option<String>,
    /// 1-based line of the attribute in the original source.
    pub line: usize,
    /// 0-based column of the attribute in the original source.
    pub column: usize,
}

/// Map from cfg keys to their known state.
///
/// Bare predicates use the key "unix"; name/value predicates use
/// feature="fast". Keys absent from the map are CfgState::Unknown.
#[derive(Clone, Debug, Default)]
pub struct ConfigEnv {
    entries: BTreeMap<String, CfgState>,
}

impl ConfigEnv {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn set(&mut self, key: impl Into<String>, state: CfgState) -> &mut Self {
        self.entries.insert(key.into(), state);
        self
    }

    pub fn get(&self, key: &str) -> CfgState {
        self.entries.get(key).copied().unwrap_or(CfgState::Unknown)
    }
}

/// Evaluator configuration and expansion budget.
#[derive(Clone, Debug)]
pub struct CfgEval {
    env: ConfigEnv,
    budget: usize,
}

impl CfgEval {
    /// Default number of cfg_attr expansions allowed per file.
    pub const DEFAULT_BUDGET: usize = 256;

    pub fn new(env: ConfigEnv) -> Self {
        Self {
            env,
            budget: Self::DEFAULT_BUDGET,
        }
    }

    /// Override the cfg_attr expansion budget.
    pub fn with_budget(mut self, budget: usize) -> Self {
        self.budget = budget;
        self
    }

    /// Rewrite file in place and return diagnostics. On error the file is
    /// left untouched because the rewrite is built on a token-level snapshot
    /// and committed only after the whole analysis succeeds.
    pub fn eval_file(&self, file: &mut File) -> Result<Vec<Diagnostic>, Error> {
        let mut rewritten = snapshot_file(file)?;
        let mut run = Run {
            cfg: self,
            remaining: self.budget,
            diagnostics: Vec::new(),
        };
        run.walk_file(&mut rewritten)?;
        *file = rewritten;
        Ok(run.diagnostics)
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
enum Eval {
    True,
    False,
    /// Kept predicate text after simplification.
    Unknown(String),
}

fn eval_cfg(env: &ConfigEnv, meta: &Meta) -> Result<Eval, Error> {
    match meta {
        Meta::Path(_) | Meta::NameValue(_) => {
            let key = meta_key(meta)?;
            Ok(match env.get(&key) {
                CfgState::True => Eval::True,
                CfgState::False => Eval::False,
                CfgState::Unknown => Eval::Unknown(key),
            })
        }
        Meta::List(list) => {
            let ident = list
                .path
                .get_ident()
                .ok_or_else(|| Error::new(list.path.span(), "unsupported cfg predicate"))?;
            let args = parse_meta_list(list)?;
            match ident.to_string().as_str() {
                "all" => {
                    let mut unknowns = Vec::new();
                    for arg in &args {
                        match eval_cfg(env, arg)? {
                            Eval::False => return Ok(Eval::False),
                            Eval::True => {}
                            Eval::Unknown(expr) => unknowns.push(expr),
                        }
                    }
                    Ok(match unknowns.len() {
                        0 => Eval::True,
                        1 => Eval::Unknown(unknowns.pop().unwrap()),
                        _ => Eval::Unknown(format!("all({})", unknowns.join(", "))),
                    })
                }
                "any" => {
                    let mut unknowns = Vec::new();
                    for arg in &args {
                        match eval_cfg(env, arg)? {
                            Eval::True => return Ok(Eval::True),
                            Eval::False => {}
                            Eval::Unknown(expr) => unknowns.push(expr),
                        }
                    }
                    Ok(match unknowns.len() {
                        0 => Eval::False,
                        1 => Eval::Unknown(unknowns.pop().unwrap()),
                        _ => Eval::Unknown(format!("any({})", unknowns.join(", "))),
                    })
                }
                "not" => match args.len() {
                    1 => Ok(match eval_cfg(env, &args[0])? {
                        Eval::True => Eval::False,
                        Eval::False => Eval::True,
                        Eval::Unknown(inner) => Eval::Unknown(format!("not({})", inner)),
                    }),
                    n => Err(Error::new(
                        list.tokens.span(),
                        format!("not takes exactly 1 argument, found {}", n),
                    )),
                },
                other => Err(Error::new(
                    ident.span(),
                    format!("unsupported cfg predicate: {}", other),
                )),
            }
        }
    }
}

fn parse_meta_list(list: &syn::MetaList) -> Result<Punctuated<Meta, Token![,]>, Error> {
    list.parse_args_with(Punctuated::<Meta, Token![,]>::parse_terminated)
        .map_err(|err| Error::new(err.span(), format!("malformed cfg expression: {}", err)))
}

fn meta_key(meta: &Meta) -> Result<String, Error> {
    match meta {
        Meta::Path(path) => {
            let ident = path
                .get_ident()
                .ok_or_else(|| Error::new(path.span(), "unsupported cfg predicate"))?;
            Ok(ident.to_string())
        }
        Meta::NameValue(nv) => {
            let ident = nv
                .path
                .get_ident()
                .ok_or_else(|| Error::new(nv.path.span(), "unsupported cfg predicate"))?;
            let value = match &nv.value {
                Expr::Lit(expr_lit) => match &expr_lit.lit {
                    Lit::Str(lit_str) => lit_str.value(),
                    _ => {
                        return Err(Error::new(
                            nv.value.span(),
                            "cfg name/value predicate requires a string literal value",
                        ));
                    }
                },
                _ => {
                    return Err(Error::new(
                        nv.value.span(),
                        "cfg name/value predicate requires a string literal value",
                    ));
                }
            };
            Ok(format!("{}={:?}", ident, value))
        }
        Meta::List(list) => Err(Error::new(
            list.path.span(),
            "nested cfg list used as a bare predicate",
        )),
    }
}

fn span_position(span: Span) -> (usize, usize) {
    let loc = span.start();
    (loc.line, loc.column)
}

// The rewrite is applied to a token-level snapshot so that a later error
// never leaves the caller's File half-rewritten.
fn snapshot_file(file: &File) -> Result<File, Error> {
    syn::parse2(quote::quote!(#file))
}

struct ParsedCfgAttr {
    condition: Meta,
    attributes: Vec<Attribute>,
}

fn parse_cfg_attr(attr: &Attribute) -> Result<ParsedCfgAttr, Error> {
    let list = match &attr.meta {
        Meta::List(list) if attr.path().is_ident("cfg_attr") => list,
        _ => {
            return Err(Error::new(
                attr.span(),
                "internal error: expected cfg_attr attribute",
            ));
        }
    };
    let args = parse_meta_list(list)?;
    let mut iter = args.into_iter();
    let condition = iter
        .next()
        .ok_or_else(|| Error::new(list.tokens.span(), "cfg_attr requires a condition predicate"))?;
    let attributes = iter
        .map(|meta| {
            let span = meta.span();
            Attribute {
                pound_token: Token![#](span),
                style: syn::AttrStyle::Outer,
                bracket_token: syn::token::Bracket(span),
                meta,
            }
        })
        .collect();
    Ok(ParsedCfgAttr {
        condition,
        attributes,
    })
}

struct Run<'a> {
    cfg: &'a CfgEval,
    remaining: usize,
    diagnostics: Vec<Diagnostic>,
}

impl<'a> Run<'a> {
    fn walk_file(&mut self, file: &mut File) -> Result<(), Error> {
        self.process_attrs(&mut file.attrs, "<crate>")?;
        let mut path = Vec::new();
        self.process_items(&mut file.items, &mut path)
    }

    fn record(
        &mut self,
        span: Span,
        path: &str,
        kind: DiagnosticKind,
        condition: Option<String>,
    ) {
        let (line, column) = span_position(span);
        self.diagnostics.push(Diagnostic {
            path: path.to_owned(),
            kind,
            condition,
            line,
            column,
        });
    }

    fn process_attrs(&mut self, attrs: &mut Vec<Attribute>, path: &str) -> Result<bool, Error> {
        self.expand_cfg_attrs(attrs, path)?;

        let mut index = 0;
        while index < attrs.len() {
            let attr = &attrs[index];
            if !attr.path().is_ident("cfg") {
                index += 1;
                continue;
            }
            let condition = match &attr.meta {
                Meta::List(list) => list.parse_args::<Meta>().map_err(|err| {
                    Error::new(err.span(), format!("malformed cfg expression: {}", err))
                })?,
                _ => {
                    return Err(Error::new(
                        attr.span(),
                        "malformed cfg expression: expected cfg(...)",
                    ));
                }
            };
            match eval_cfg(&self.cfg.env, &condition)? {
                Eval::True => {
                    attrs.remove(index);
                }
                Eval::False => {
                    attrs.remove(index);
                    return Ok(false);
                }
                Eval::Unknown(simplified) => {
                    self.record(
                        attr.span(),
                        path,
                        DiagnosticKind::UnknownCondition,
                        Some(simplified),
                    );
                    index += 1;
                }
            }
        }
        Ok(true)
    }

    /// Repeatedly apply cfg_attr so generated attributes are processed too.
    fn expand_cfg_attrs(
        &mut self,
        attrs: &mut Vec<Attribute>,
        path: &str,
    ) -> Result<(), Error> {
        let mut index = 0;
        while index < attrs.len() {
            let attr = &attrs[index];
            if !attr.path().is_ident("cfg_attr") {
                index += 1;
                continue;
            }
            let parsed = parse_cfg_attr(attr)?;
            match eval_cfg(&self.cfg.env, &parsed.condition)? {
                Eval::True => {
                    if self.remaining == 0 {
                        return Err(Error::new(
                            attr.span(),
                            "cfg_attr expansion budget exceeded",
                        ));
                    }
                    self.remaining -= 1;
                    let generated = parsed.attributes;
                    attrs.splice(index..index + 1, generated);
                    // Re-inspect the inserted attributes from the same index.
                }
                Eval::False => {
                    attrs.remove(index);
                }
                Eval::Unknown(simplified) => {
                    self.record(
                        attr.span(),
                        path,
                        DiagnosticKind::UnknownCondition,
                        Some(simplified),
                    );
                    index += 1;
                }
            }
        }
        Ok(())
    }

    fn process_items(
        &mut self,
        items: &mut Vec<Item>,
        path: &mut Vec<String>,
    ) -> Result<(), Error> {
        let old = mem::take(items);
        for mut item in old {
            let name = item_name(&item);
            path.push(name);
            let item_path = path.join("::");
            if is_verbatim_item(&item) {
                return Err(Error::new(item.span(), "cfg cannot be evaluated on verbatim item"));
            }
            let attrs = item_attrs(&mut item).unwrap();
            let keep = self.process_attrs(attrs, &item_path)?;
            if keep {
                self.recurse_item(&mut item, path, &item_path)?;
                items.push(item);
            }
            path.pop();
        }
        Ok(())
    }

    fn recurse_item(
        &mut self,
        item: &mut Item,
        path: &mut Vec<String>,
        item_path: &str,
    ) -> Result<(), Error> {
        match item {
            Item::Mod(module) => match &mut module.content {
                Some((_, items)) => self.process_items(items, path),
                None => {
                    self.record(
                        module.mod_token.span,
                        item_path,
                        DiagnosticKind::ExternalModule,
                        None,
                    );
                    Ok(())
                }
            },
            Item::Enum(item_enum) => self.process_variants(&mut item_enum.variants, item_path),
            Item::Struct(item_struct) => self.process_fields(&mut item_struct.fields, item_path),
            Item::Union(item_union) => {
                self.filter_fields(&mut item_union.fields.named, item_path)
            }
            Item::Impl(item_impl) => self.process_impl_items(&mut item_impl.items, item_path),
            Item::Trait(item_trait) => self.process_trait_items(&mut item_trait.items, item_path),
            Item::ForeignMod(foreign) => {
                self.process_foreign_items(&mut foreign.items, item_path)
            }
            _ => Ok(()),
        }
    }

    fn process_variants(
        &mut self,
        variants: &mut Punctuated<Variant, Token![,]>,
        item_path: &str,
    ) -> Result<(), Error> {
        let old = mem::take(variants);
        let mut kept = Vec::new();
        for pair in old.into_pairs() {
            let (mut variant, comma) = pair.into_tuple();
            let variant_path = format!("{}::{}", item_path, variant.ident);
            if self.process_attrs(&mut variant.attrs, &variant_path)? {
                self.process_fields(&mut variant.fields, &variant_path)?;
                kept.push(Pair::new(variant, comma));
            }
        }
        *variants = kept.into_iter().collect();
        Ok(())
    }

    fn process_fields(&mut self, fields: &mut Fields, item_path: &str) -> Result<(), Error> {
        match fields {
            Fields::Named(named) => self.filter_fields(&mut named.named, item_path),
            Fields::Unnamed(unnamed) => self.filter_fields(&mut unnamed.unnamed, item_path),
            Fields::Unit => Ok(()),
        }
    }

    fn filter_fields(
        &mut self,
        fields: &mut Punctuated<Field, Token![,]>,
        item_path: &str,
    ) -> Result<(), Error> {
        let old = mem::take(fields);
        let mut kept = Vec::new();
        for (index, pair) in old.into_pairs().enumerate() {
            let (mut field, comma) = pair.into_tuple();
            let field_name = field
                .ident
                .as_ref()
                .map(|ident| ident.to_string())
                .unwrap_or_else(|| index.to_string());
            let field_path = format!("{}::{}", item_path, field_name);
            if self.process_attrs(&mut field.attrs, &field_path)? {
                kept.push(Pair::new(field, comma));
            }
        }
        *fields = kept.into_iter().collect();
        Ok(())
    }

    fn process_impl_items(
        &mut self,
        items: &mut Vec<ImplItem>,
        item_path: &str,
    ) -> Result<(), Error> {
        let old = mem::take(items);
        for mut child in old {
            let name = impl_item_name(&child);
            let child_path = format!("{}::{}", item_path, name);
            if is_verbatim_impl_item(&child) {
                return Err(Error::new(
                    child.span(),
                    "cfg cannot be evaluated on verbatim impl item",
                ));
            }
            let attrs = impl_item_attrs(&mut child).unwrap();
            if self.process_attrs(attrs, &child_path)? {
                items.push(child);
            }
        }
        Ok(())
    }

    fn process_trait_items(
        &mut self,
        items: &mut Vec<TraitItem>,
        item_path: &str,
    ) -> Result<(), Error> {
        let old = mem::take(items);
        for mut child in old {
            let name = trait_item_name(&child);
            let child_path = format!("{}::{}", item_path, name);
            if is_verbatim_trait_item(&child) {
                return Err(Error::new(
                    child.span(),
                    "cfg cannot be evaluated on verbatim trait item",
                ));
            }
            let attrs = trait_item_attrs(&mut child).unwrap();
            if self.process_attrs(attrs, &child_path)? {
                items.push(child);
            }
        }
        Ok(())
    }

    fn process_foreign_items(
        &mut self,
        items: &mut Vec<ForeignItem>,
        item_path: &str,
    ) -> Result<(), Error> {
        let old = mem::take(items);
        for mut child in old {
            let name = foreign_item_name(&child);
            let child_path = format!("{}::{}", item_path, name);
            if is_verbatim_foreign_item(&child) {
                return Err(Error::new(
                    child.span(),
                    "cfg cannot be evaluated on verbatim foreign item",
                ));
            }
            let attrs = foreign_item_attrs(&mut child).unwrap();
            if self.process_attrs(attrs, &child_path)? {
                items.push(child);
            }
        }
        Ok(())
    }
}

fn item_name(item: &Item) -> String {
    match item {
        Item::Const(item) => item.ident.to_string(),
        Item::Enum(item) => item.ident.to_string(),
        Item::ExternCrate(item) => item.ident.to_string(),
        Item::Fn(item) => item.sig.ident.to_string(),
        Item::ForeignMod(_) => "extern".to_owned(),
        Item::Impl(_) => "impl".to_owned(),
        Item::Macro(item) => macro_name(&item.mac.path),
        Item::Mod(item) => item.ident.to_string(),
        Item::Static(item) => item.ident.to_string(),
        Item::Struct(item) => item.ident.to_string(),
        Item::Trait(item) => item.ident.to_string(),
        Item::TraitAlias(item) => item.ident.to_string(),
        Item::Type(item) => item.ident.to_string(),
        Item::Union(item) => item.ident.to_string(),
        Item::Use(_) => "use".to_owned(),
        Item::Verbatim(_) => "<verbatim>".to_owned(),
        _ => "<item>".to_owned(),
    }
}

fn item_attrs(item: &mut Item) -> Option<&mut Vec<Attribute>> {
    match item {
        Item::Const(item) => Some(&mut item.attrs),
        Item::Enum(item) => Some(&mut item.attrs),
        Item::ExternCrate(item) => Some(&mut item.attrs),
        Item::Fn(item) => Some(&mut item.attrs),
        Item::ForeignMod(item) => Some(&mut item.attrs),
        Item::Impl(item) => Some(&mut item.attrs),
        Item::Macro(item) => Some(&mut item.attrs),
        Item::Mod(item) => Some(&mut item.attrs),
        Item::Static(item) => Some(&mut item.attrs),
        Item::Struct(item) => Some(&mut item.attrs),
        Item::Trait(item) => Some(&mut item.attrs),
        Item::TraitAlias(item) => Some(&mut item.attrs),
        Item::Type(item) => Some(&mut item.attrs),
        Item::Union(item) => Some(&mut item.attrs),
        Item::Use(item) => Some(&mut item.attrs),
        Item::Verbatim(_) => None,
        _ => None,
    }
}

fn is_verbatim_item(item: &Item) -> bool {
    matches!(item, Item::Verbatim(_))
}

fn macro_name(path: &syn::Path) -> String {
    path.segments
        .last()
        .map(|segment| segment.ident.to_string())
        .unwrap_or_else(|| "<macro>".to_owned())
}

